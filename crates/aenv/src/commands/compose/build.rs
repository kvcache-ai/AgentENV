//! `aenv compose build`: plans a Compose project locally, builds every service
//! that declares `build` like `aenv build --image`, and writes a Compose
//! override file that points those services at their published images, so the
//! project starts from them without building again.
//! `aenv compose up` builds services the same way.

use super::plan::{self, ProjectArgs};
use crate::client::Client;
use crate::commands::build::{BuildkitArgs, ImageOptions, RegistryPush, ServiceImage};
use anyhow::{ensure, Context, Result};
use clap::Args as ClapArgs;
use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::io::Write;
use std::path::{Path, PathBuf};

/// First line of every override file, which marks a file `aenv compose build`
/// may replace.
const OVERRIDE_HEADER: &str = "# Generated by aenv compose build.";

#[derive(ClapArgs)]
#[command(after_help = "Examples:
  aenv compose build
  aenv compose up -f compose.yaml -f compose.aenv.yaml
  aenv compose build -f compose.yaml -f compose.prod.yaml --output prod.aenv.yaml

The project is loaded as Docker Compose loads it, including the process
environment and the project's .env file. Each service that declares build: is
built with the server's builder and published as aenv/PROJECT-SERVICE:latest.
After every build succeeds, the command writes a Compose override file that
pins those services, and services that use the image one of them builds, to
the built image digests. Add it after the project's Compose files to start the
project without building again; the original files are not modified.")]
pub(super) struct BuildArgs {
    #[command(flatten)]
    project: ProjectArgs,
    /// Override file to write; an existing file is replaced only if an earlier
    /// aenv compose build wrote it [default: compose.aenv.yaml in the project
    /// directory]
    #[arg(long, value_name = "PATH")]
    output: Option<PathBuf>,
    /// Also push each image to a unique tag in this registry repository, e.g.
    /// registry.example.com/team/images, and reference that tag
    #[arg(long, value_name = "REGISTRY/REPOSITORY")]
    image_repository: Option<String>,
    /// Allow HTTP or untrusted TLS for image pushes (development registries only)
    #[arg(long, requires = "image_repository")]
    registry_insecure: bool,
    #[command(flatten)]
    buildkit: BuildkitArgs,
}

fn validate_repository(repository: &str) -> Result<()> {
    let (host, path) = repository
        .split_once('/')
        .context("--image-repository must include a registry host and repository path")?;
    ensure!(
        !host.is_empty()
            && (host.contains('.') || host.contains(':') || host == "localhost")
            && host
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b".-:".contains(&b))
            && !path.is_empty()
            && path.len() <= 200
            && path.split('/').all(|part| !part.is_empty()
                && part
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b"._-".contains(&b))),
        "invalid --image-repository; use REGISTRY/REPOSITORY without a scheme, tag, or digest"
    );
    Ok(())
}

/// Lowercase letters and digits joined by single `.`, `_`, or `-`, as image
/// names require.
fn normalize_name(value: &str) -> String {
    let mut name = String::new();
    for c in value.chars().map(|c| c.to_ascii_lowercase()) {
        if c.is_ascii_lowercase() || c.is_ascii_digit() {
            name.push(c);
        } else if !name.is_empty() && !name.ends_with(['.', '_', '-']) {
            name.push(if matches!(c, '.' | '_') { c } else { '-' });
        }
    }
    name.trim_end_matches(['.', '_', '-']).to_owned()
}

/// Like Docker Compose, names each service's image PROJECT-SERVICE.
fn image_names<'a>(
    project: &str,
    services: impl IntoIterator<Item = &'a str>,
) -> Result<Vec<String>> {
    let prefix = normalize_name(project);
    ensure!(
        !prefix.is_empty(),
        "cannot derive an image name from project {project:?}; set --project-name"
    );
    let mut seen = HashSet::new();
    services
        .into_iter()
        .map(|service| {
            let name = normalize_name(&format!("{prefix}-{service}"));
            ensure!(
                name.len() <= 128,
                "image name {name} exceeds 128 characters; set a shorter --project-name"
            );
            ensure!(
                seen.insert(name.clone()),
                "several services map to image name {name}; rename one of them"
            );
            Ok(name)
        })
        .collect()
}

/// The services that declare build, in plan order.
fn builds(plan: &plan::Plan) -> impl Iterator<Item = (&str, &plan::Build)> {
    plan.services
        .iter()
        .filter_map(|service| Some((service.name.as_str(), service.build.as_ref()?)))
}

/// Adds the services that run the image another service builds.
fn with_built_by(
    plan: &plan::Plan,
    mut images: BTreeMap<String, String>,
) -> BTreeMap<String, String> {
    for service in &plan.services {
        let image = service
            .built_by
            .as_ref()
            .and_then(|builder| images.get(builder))
            .cloned();
        if let Some(image) = image {
            images.insert(service.name.clone(), image);
        }
    }
    images
}

/// Maps each service that declares build, or runs the image another service
/// builds, to the `latest` tag of the built image, which `aenv compose build`
/// and `aenv compose up` publish.
pub(super) fn latest_images(plan: &plan::Plan) -> Result<BTreeMap<String, String>> {
    let services: Vec<_> = builds(plan).map(|(name, _)| name).collect();
    let names = image_names(&plan.project_name, services.iter().copied())?;
    let images = services
        .into_iter()
        .zip(names)
        .map(|(service, name)| (service.to_owned(), format!("aenv/{name}:latest")))
        .collect();
    Ok(with_built_by(plan, images))
}

/// Writes an inline Dockerfile into a new directory, which must outlive the
/// build.
fn inline_dockerfile(content: &str) -> Result<(tempfile::TempDir, PathBuf)> {
    let directory = tempfile::tempdir().context("preparing the inline Dockerfile")?;
    let path = directory.path().join("Dockerfile");
    std::fs::write(&path, content).context("writing the inline Dockerfile")?;
    Ok((directory, path))
}

/// Builds each service that declares build like `aenv build --image`, one at
/// a time, and maps it, and the services that run its image, to its image
/// digest, or with `repository` to a unique pushed tag.
pub(super) async fn build_services(
    client: &Client,
    plan: &plan::Plan,
    buildkit: &BuildkitArgs,
    repository: Option<&str>,
    registry_insecure: bool,
) -> Result<BTreeMap<String, String>> {
    let services: Vec<_> = builds(plan).collect();
    let names = image_names(&plan.project_name, services.iter().map(|(name, _)| *name))?;

    // Validate every context and Dockerfile before the first build. As in
    // Compose, Dockerfiles resolve against their context.
    let id = uuid::Uuid::new_v4().simple().to_string();
    let mut images = Vec::new();
    // Inline Dockerfiles must remain until every build completes.
    let mut inline = Vec::new();
    for (index, ((service, build), name)) in services.into_iter().zip(names).enumerate() {
        let pushed = repository.map(|repository| format!("{repository}:aenv-{id}-{index}"));
        let mut buildkit = buildkit.clone();
        buildkit.no_cache |= build.no_cache;
        let dockerfile = match &build.dockerfile_inline {
            Some(content) => {
                let (directory, path) = inline_dockerfile(content)?;
                inline.push(directory);
                path
            }
            None => build.context.join(&build.dockerfile),
        };
        let image = ServiceImage::prepare(
            name,
            &build.context,
            &dockerfile,
            build
                .args
                .iter()
                .map(|(key, value)| format!("{key}={value}"))
                .collect(),
            buildkit,
            ImageOptions {
                target: build.target.clone(),
                push: pushed.clone().map(|image| RegistryPush {
                    image,
                    insecure: registry_insecure,
                }),
            },
        )
        .with_context(|| format!("service {service}"))?;
        images.push((service, image, pushed));
    }

    // Each published image remains usable if a later service fails.
    let mut built = BTreeMap::new();
    for (service, image, pushed) in images {
        match &pushed {
            Some(tag) => eprintln!(
                "Building Compose service {service} as aenv/{} -> {tag}",
                image.name()
            ),
            None => eprintln!(
                "Building Compose service {service} as aenv/{}",
                image.name()
            ),
        }
        let digest = image
            .build(client)
            .await
            .with_context(|| format!("building Compose service {service}"))?;
        built.insert(service.to_owned(), pushed.unwrap_or(digest));
    }
    Ok(with_built_by(plan, built))
}

/// Whether `output` is absent or an override file an earlier `aenv compose
/// build` wrote, which may be replaced.
fn replaceable(output: &Path) -> Result<bool> {
    match std::fs::read(output) {
        Ok(content) => Ok(content.starts_with(format!("{OVERRIDE_HEADER}\n").as_bytes())),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(true),
        Err(error) => Err(error).with_context(|| format!("reading {}", output.display())),
    }
}

/// The command that starts the project with the override file after its
/// Compose files and with the build's project options, except `--env`, whose
/// values may be secrets.
fn up_command(plan: &plan::Plan, project: &ProjectArgs, output: &Path) -> String {
    let path = |path: &Path| shell_util::shell_quote(&path.display().to_string());
    let mut command = String::from("aenv compose up");
    for file in plan
        .compose_files
        .iter()
        .map(PathBuf::as_path)
        .chain([output])
    {
        command.push_str(&format!(" -f {}", path(file)));
    }
    command.push_str(&format!(
        " --project-directory {} -p {}",
        path(&plan.project_directory),
        shell_util::shell_quote(&plan.project_name)
    ));
    for file in &project.env_files {
        let file = std::path::absolute(file).unwrap_or_else(|_| file.clone());
        command.push_str(&format!(" --env-file {}", path(&file)));
    }
    for profile in &project.profiles {
        command.push_str(&format!(" --profile {}", shell_util::shell_quote(profile)));
    }
    command
}

/// A Compose override file that points each service in `images` at its image
/// and removes the build of each service that declares one. Values are JSON
/// strings, which YAML reads unchanged.
fn override_file(
    plan: &plan::Plan,
    project: &ProjectArgs,
    images: &BTreeMap<String, String>,
    output: &Path,
) -> String {
    let quote = |value: &str| serde_json::Value::from(value).to_string();
    let mut content = format!(
        "{OVERRIDE_HEADER}\n# Start the project from the built images with:\n#   {}\nservices:\n",
        up_command(plan, project, output)
    );
    for service in &plan.services {
        let Some(image) = images.get(&service.name) else {
            continue;
        };
        let (name, image) = (quote(&service.name), quote(image));
        content.push_str(&format!("  {name}:\n    image: {image}\n"));
        if service.build.is_some() {
            content.push_str("    build: !reset null\n    pull_policy: !reset null\n");
        }
    }
    content
}

/// Moves the written override file to `output`. A file created there during
/// the build is never replaced, and an existing one only if an earlier
/// `aenv compose build` wrote it.
fn publish(destination: tempfile::NamedTempFile, output: &Path) -> Result<()> {
    let persisted = if std::fs::symlink_metadata(output).is_ok() {
        ensure!(
            replaceable(output)?,
            "{} was created during the build; choose another --output",
            output.display()
        );
        destination.persist(output)
    } else {
        destination.persist_noclobber(output)
    };
    persisted.with_context(|| format!("writing override file {}", output.display()))?;
    Ok(())
}

pub(super) fn run(mut args: BuildArgs) -> Result<()> {
    args.buildkit.check()?;
    if let Some(repository) = &args.image_repository {
        validate_repository(repository)?;
    }
    let rt = crate::commands::tokio_rt()?;
    let planned = rt.block_on(args.project.plan_builds())?;
    ensure!(
        builds(&planned).next().is_some(),
        "no selected service declares build; run aenv compose up directly"
    );
    let output = args
        .output
        .clone()
        .unwrap_or_else(|| planned.project_directory.join("compose.aenv.yaml"));
    // Refuse another file before allocating builders.
    ensure!(
        replaceable(&output)?,
        "{} exists and was not written by aenv compose build; choose another --output",
        output.display()
    );
    let parent = output
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut destination =
        tempfile::NamedTempFile::new_in(parent).context("preparing the override file")?;
    let client = Client::from_env()?;
    let images = rt.block_on(build_services(
        &client,
        &planned,
        &args.buildkit,
        args.image_repository.as_deref(),
        args.registry_insecure,
    ))?;
    destination.write_all(override_file(&planned, &args.project, &images, &output).as_bytes())?;
    destination.as_file().sync_all()?;
    publish(destination, &output)?;
    eprintln!("Wrote Compose override file: {}", output.display());
    eprintln!(
        "Start the project with: {}",
        up_command(&planned, &args.project, &output)
    );
    for reminder in reminders(&planned, &args.project) {
        eprintln!("{reminder}");
    }
    Ok(())
}

/// What the printed command cannot repeat: `--env` values, which may be
/// secrets, and a Compose file read from stdin.
fn reminders(plan: &plan::Plan, project: &ProjectArgs) -> Vec<String> {
    let mut reminders = Vec::new();
    let variables: BTreeSet<_> = project
        .environment
        .iter()
        .map(|(key, _)| key.as_str())
        .collect();
    if !variables.is_empty() {
        let variables: Vec<_> = variables.into_iter().collect();
        reminders.push(format!("Pass --env again for {}", variables.join(", ")));
    }
    if plan.compose_files.iter().any(|file| file == Path::new("-")) {
        reminders.push("Pass the same Compose file on stdin again".to_owned());
    }
    reminders
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::{CommandFactory, Parser};
    use serde_json::json;

    fn parse(arguments: &str) -> Result<BuildArgs, clap::Error> {
        match crate::Cli::try_parse_from(arguments.split_whitespace())?.cmd {
            crate::Cmd::Compose(super::super::Args {
                cmd: super::super::Sub::Build(args),
            }) => Ok(args),
            _ => panic!("expected compose build"),
        }
    }

    #[test]
    fn parses_build_flags() {
        crate::Cli::command().debug_assert();
        let args = parse(
            "aenv compose build -f env/compose.yaml -f env/extra.yaml -p task --output out.yaml \
             --env TAG=a=b --env-file prod.env --profile worker --planner /opt/plan \
             --image-repository example.com/team/images --registry-insecure \
             --no-cache --timeout 600 --progress plain",
        )
        .unwrap();
        assert_eq!(
            args.project.files,
            [
                PathBuf::from("env/compose.yaml"),
                PathBuf::from("env/extra.yaml")
            ]
        );
        assert_eq!(args.project.project_name.as_deref(), Some("task"));
        assert_eq!(args.output, Some(PathBuf::from("out.yaml")));
        assert_eq!(args.project.environment, [("TAG".into(), "a=b".into())]);
        assert_eq!(args.project.env_files, [PathBuf::from("prod.env")]);
        assert_eq!(args.project.profiles, ["worker"]);
        assert!(args.registry_insecure && args.buildkit.no_cache);
        assert_eq!(args.project.planner, Some(PathBuf::from("/opt/plan")));
        assert_eq!(
            args.image_repository.as_deref(),
            Some("example.com/team/images")
        );
        let defaults = parse("aenv compose build").unwrap();
        assert!(defaults.project.files.is_empty());
        assert!(defaults.project.project_name.is_none() && defaults.output.is_none());
        assert!(!defaults.buildkit.no_cache);
        for invalid in [
            "aenv compose build --registry-insecure",
            "aenv compose build --env =value",
            "aenv compose build --timeout 0",
            "aenv compose build --build-arg A=B",
            "aenv compose build --image",
        ] {
            assert!(parse(invalid).is_err(), "{invalid}");
        }
    }

    #[test]
    fn service_images_are_named_like_docker_compose() {
        assert_eq!(
            image_names("My_App", ["web", "Worker.1"]).unwrap(),
            ["my_app-web", "my_app-worker.1"]
        );
        assert_eq!(
            image_names("--odd  name--", ["db"]).unwrap(),
            ["odd-name-db"]
        );
        assert!(image_names("___", ["web"]).is_err());
        assert!(image_names("app", ["Web", "web"]).is_err());
        assert!(image_names(&"a".repeat(126), ["web"]).is_err());
    }

    #[test]
    fn without_building_services_use_their_latest_images() {
        let plan: plan::Plan = serde_json::from_value(json!({
            "projectName": "my_app",
            "projectDirectory": "/work/my_app",
            "composeFiles": ["/work/my_app/compose.yaml"],
            "compose": {"services": {"app": {}, "db": {"image": "postgres:17"}}},
            "services": [
                {"name": "app", "image": "example/app:dev",
                 "build": {"context": "/work/my_app", "dockerfile": "Dockerfile"}},
                {"name": "db", "image": "postgres:17"},
                {"name": "sidecar", "image": "example/app:dev", "builtBy": "app"},
            ],
        }))
        .unwrap();
        assert_eq!(
            latest_images(&plan).unwrap(),
            BTreeMap::from([
                ("app".to_owned(), "aenv/my_app-app:latest".to_owned()),
                ("sidecar".to_owned(), "aenv/my_app-app:latest".to_owned()),
            ])
        );
    }

    #[test]
    fn override_file_points_services_at_the_built_images() {
        let plan: plan::Plan = serde_json::from_value(json!({
            "projectName": "app",
            "projectDirectory": "/work/my app",
            "composeFiles": ["/work/my app/compose.yaml", "/work/my app/compose.prod.yaml"],
            "compose": {"services": {}},
            "services": [
                {"name": "app", "image": "example/app:dev",
                 "build": {"context": "/work/my app", "dockerfile": "Dockerfile"}},
                {"name": "db", "image": "postgres:17"},
                {"name": "sidecar", "image": "example/app:dev", "builtBy": "app"},
            ],
        }))
        .unwrap();
        let digest = format!("sha256:{}", "a".repeat(64));
        let images = BTreeMap::from([
            ("app".to_owned(), digest.clone()),
            ("sidecar".to_owned(), digest.clone()),
        ]);
        let output = Path::new("/work/my app/compose.aenv.yaml");
        let project = parse(
            "aenv compose build -p app --env-file prod.env --profile debug --profile worker \
             --env TOKEN=secret",
        )
        .unwrap()
        .project;
        let env_file = std::path::absolute("prod.env").unwrap();
        let up = format!(
            "aenv compose up -f '/work/my app/compose.yaml' \
             -f '/work/my app/compose.prod.yaml' -f '/work/my app/compose.aenv.yaml' \
             --project-directory '/work/my app' -p app \
             --env-file {} --profile debug --profile worker",
            shell_util::shell_quote(&env_file.display().to_string())
        );
        assert_eq!(up_command(&plan, &project, output), up);
        assert!(!up.contains("secret"));
        assert_eq!(
            override_file(&plan, &project, &images, output),
            format!(
                "{OVERRIDE_HEADER}\n# Start the project from the built images with:\n#   {up}\n\
                 services:\n  \"app\":\n    image: \"{digest}\"\n    build: !reset null\n    \
                 pull_policy: !reset null\n  \"sidecar\":\n    image: \"{digest}\"\n"
            )
        );
    }

    #[test]
    fn reminds_what_the_command_cannot_repeat() {
        let planned = |files: serde_json::Value| -> plan::Plan {
            serde_json::from_value(json!({
                "projectName": "app", "projectDirectory": "/work/app", "composeFiles": files,
                "compose": {"services": {}}, "services": [],
            }))
            .unwrap()
        };
        let quiet = parse("aenv compose build").unwrap().project;
        assert!(reminders(&planned(json!(["/work/app/compose.yaml"])), &quiet).is_empty());
        let project = parse("aenv compose build --env TOKEN=a --env A=1 --env TOKEN=b")
            .unwrap()
            .project;
        assert_eq!(
            reminders(&planned(json!(["-", "/work/app/extra.yaml"])), &project),
            [
                "Pass --env again for A, TOKEN",
                "Pass the same Compose file on stdin again"
            ]
        );
    }

    #[test]
    fn replaces_only_generated_override_files() {
        let work = tempfile::tempdir().unwrap();
        let output = work.path().join("compose.aenv.yaml");
        assert!(replaceable(&output).unwrap());
        std::fs::write(&output, format!("{OVERRIDE_HEADER}\nservices: {{}}\n")).unwrap();
        assert!(replaceable(&output).unwrap());
        std::fs::write(&output, "services: {}\n").unwrap();
        assert!(!replaceable(&output).unwrap());
    }

    #[test]
    fn publishing_replaces_only_generated_override_files() {
        let work = tempfile::tempdir().unwrap();
        let output = work.path().join("compose.aenv.yaml");
        let written = |content: &str| {
            let mut file = tempfile::NamedTempFile::new_in(work.path()).unwrap();
            file.write_all(content.as_bytes()).unwrap();
            file
        };
        let generated = format!("{OVERRIDE_HEADER}\nservices: {{}}\n");
        publish(written(&generated), &output).unwrap();
        assert_eq!(std::fs::read_to_string(&output).unwrap(), generated);
        let again = format!("{generated}# again\n");
        publish(written(&again), &output).unwrap();
        assert_eq!(std::fs::read_to_string(&output).unwrap(), again);
        std::fs::write(&output, "services: {}\n").unwrap();
        assert!(publish(written(&generated), &output).is_err());
        assert_eq!(std::fs::read_to_string(&output).unwrap(), "services: {}\n");
    }

    #[test]
    fn inline_dockerfiles_are_written_for_the_build() {
        let (directory, path) = inline_dockerfile("FROM busybox\n").unwrap();
        assert_eq!(path, directory.path().join("Dockerfile"));
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "FROM busybox\n");
        drop(directory);
        assert!(!path.exists());
    }

    #[test]
    fn repository_cannot_inject_exporter_options_or_reuse_a_tag() {
        for value in [
            "example.com/team/images",
            "localhost:5000/images",
            "192.0.2.10:5000/build",
        ] {
            assert!(validate_repository(value).is_ok(), "{value}");
        }
        for value in [
            "images",
            "https://example.com/images",
            "example.com/images:latest",
            "example.com/images,push=false",
            "example.com//images",
            "example.com/images@sha256:abc",
            "example.com/Upper",
        ] {
            assert!(validate_repository(value).is_err(), "{value}");
        }
    }
}
