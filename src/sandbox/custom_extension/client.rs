    fn find_sub(hay: &[u8], needle: &[u8]) -> Option<usize> {
        hay.windows(needle.len()).position(|w| w == needle)
    }

    /// Read one HTTP request from `stream`, report `(request_line, body)` to
    /// `tx`, and reply with the given status code and JSON body.
    async fn handle_one_request(
        mut stream: tokio::net::TcpStream,
        status: u16,
        body: String,
        tx: mpsc::Sender<(String, String)>,
    ) {
        let mut buf = vec![0u8; 64 * 1024];
        let mut total = 0usize;
        let header_end = loop {
            let n = stream.read(&mut buf[total..]).await.unwrap();
            assert!(n > 0, "connection closed before headers complete");
            total += n;
            if let Some(pos) = find_sub(&buf[..total], b"\r\n\r\n") {
                break pos;
            }
        };
        let headers = String::from_utf8_lossy(&buf[..header_end]).to_string();
        let content_length = headers
            .lines()
            .skip(1)
            .filter_map(|line| line.split_once(':'))
            .find(|(name, _)| name.trim().eq_ignore_ascii_case("content-length"))
            .and_then(|(_, value)| value.trim().parse::<usize>().ok())
            .unwrap_or(0);
        let mut body_bytes = buf[header_end + 4..total].to_vec();
        while body_bytes.len() < content_length {
            let mut tmp = vec![0u8; 64 * 1024];
            let n = stream.read(&mut tmp).await.unwrap();
            assert!(n > 0, "connection closed before body complete");
            body_bytes.extend_from_slice(&tmp[..n]);
        }
        let request_line = headers.lines().next().unwrap().to_string();
        let body_str = String::from_utf8_lossy(&body_bytes[..content_length]).to_string();
        tx.send((request_line, body_str)).unwrap();
        let status_text = match status {
            200 => "OK",
            500 => "Internal Server Error",
            _ => "Unknown",
        };
        let response = format!(
            "HTTP/1.1 {status} {status_text}\r\n\
             Content-Type: application/json\r\n\
             Content-Length: {}\r\n\
             Connection: close\r\n\r\n{}",
            body.len(),
            body
        );
        stream.write_all(response.as_bytes()).await.unwrap();
    }

    /// Spawn an HTTP server that captures `request_count` sequential requests
    /// and replies to each with the given status code and JSON body. Returns
    /// the base URL and a receiver for `(request_line, body)`.
    pub(crate) async fn spawn_test_server(
        status: u16,
        body: String,
        request_count: usize,
    ) -> (String, mpsc::Receiver<(String, String)>) {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let addr = listener.local_addr().unwrap();
        let (tx, rx) = mpsc::channel();
        tokio::spawn(async move {
            for _ in 0..request_count {
                let (stream, _) = listener.accept().await.unwrap();
                handle_one_request(stream, status, body.clone(), tx.clone()).await;
            }
        });
        (format!("http://{addr}"), rx)
    }

    /// Spawn a one-shot HTTP server that captures a single request and replies
    /// with the given status code and JSON body. Returns the base URL and a
    /// receiver for `(request_line, body)`.
    pub(crate) async fn spawn_one_shot_server(
        status: u16,
        body: String,
    ) -> (String, mpsc::Receiver<(String, String)>) {
        spawn_test_server(status, body, 1).await
    }

