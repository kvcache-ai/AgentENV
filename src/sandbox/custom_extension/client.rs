//! Custom extension client: sandbox lifecycle hooks.
//!
//! The custom extension is an external HTTP service configured via
//! `[custom_extension].url`. Its only current capability is sandbox lifecycle
//! hooks, invoked by the sandbox runtime (currently the Firecracker backend):
//!
//! - `POST {url}/sandbox-hook/start-fresh` — before a fresh sandbox boots
//!   (may return extra boot args),
//! - `POST {url}/sandbox-hook/start-resume` — before a sandbox resumes from
//!   a snapshot,
//! - `POST {url}/sandbox-hook/patch-params` — applies an extension-defined
//!   patch to the custom extension params: the patch document is passed
//!   through verbatim and the hook returns the updated full params, which
//!   the runtime stores as the new current value; a failure rejects the
//!   patch,
//! - `POST {url}/sandbox-hook/stop` — when a sandbox stops, before its
//!   network slot is released (best-effort: failures are only logged).
//!
//! Sandbox ids are reused across pause/resume cycles, so each start hook
//! (start-fresh / start-resume) carries a fresh [`SandboxInstanceId`]
//! generated by the sandbox runtime, and the stop hook carries the instance
//! id of the instance being torn down. The extension should treat
//! `(sandbox_id, sandbox_instance_id)` as the identity of a running instance
//! and ignore stop notifications whose instance id is not the latest started
//! instance for that sandbox (stop delivery is best-effort and may be
//! reordered relative to a newer start).
//!
//! Except for the best-effort stop hook, any hook failure (connection error,
//! timeout, non-2xx) fails the corresponding sandbox operation. The client is
//! a process-wide singleton derived from the global config; when no URL is
//! configured, all calls are skipped.

