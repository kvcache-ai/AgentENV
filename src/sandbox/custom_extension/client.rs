    #[tokio::test]
    async fn failed_start_still_stops_on_drop_with_matching_instance_id() {
        // The instance id is recorded before the start hook is delivered, so
        // even a failed start (e.g. the extension processed the request but
        // its response was lost) gets a matching stop on teardown; an
        // extension that never processed the start ignores it.
        let (base, rx) = spawn_test_server(500, "{}".to_string(), 2).await;
        let client = test_client(&base);
        let sandbox_id = SandboxId::new();

        {
            let mut guard = CustomExtensionHookGuard::new(Arc::new(client), sandbox_id);
            guard
                .start_fresh(
                    "/var/run/netns/agentenv-ns-test",
                    Ipv4Addr::new(10, 11, 0, 129),
                    None,
                )
                .await
                .expect_err("start-fresh hook must fail on non-2xx");
        } // dropped while armed: must fire the stop hook fire-and-forget

        let (start_request_line, start_body) = rx.recv().unwrap();
        assert_eq!(
            start_request_line,
            "POST /sandbox-hook/start-fresh HTTP/1.1"
        );
        // The notification is spawned on this runtime; poll for it without
        // blocking the (single-threaded) test runtime.
        let (request_line, body) = tokio::time::timeout(std::time::Duration::from_secs(5), async {
            loop {
                if let Ok(msg) = rx.try_recv() {
                    break msg;
                }
                tokio::task::yield_now().await;
            }
        })
        .await
        .expect("stop hook should fire on drop even after a failed start");
        assert_eq!(request_line, "POST /sandbox-hook/stop HTTP/1.1");
        let start_json: serde_json::Value = serde_json::from_str(&start_body).unwrap();
        let json: serde_json::Value = serde_json::from_str(&body).unwrap();
        assert_eq!(json["sandboxId"], sandbox_id.to_string());
        assert_eq!(json["sandboxInstanceId"], start_json["sandboxInstanceId"]);
    }

