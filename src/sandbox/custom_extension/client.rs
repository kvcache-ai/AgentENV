/// Unique identifier of one runtime instance of a sandbox, internal to the
/// custom extension lifecycle hooks.
///
/// A fresh value is generated for every sandbox start (fresh boot or resume
/// from a snapshot) when the start hook is delivered; the matching stop hook
/// carries the same value. Together with the sandbox id it disambiguates
/// lifecycle hooks for sandboxes whose id is reused across pause/resume.
#[derive(Clone, Copy, Debug)]
struct SandboxInstanceId(Uuid);

impl SandboxInstanceId {
    fn new() -> Self {
        Self(Uuid::now_v7())
    }
}

impl std::fmt::Display for SandboxInstanceId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.0.fmt(f)
    }
}

/// Process-wide custom extension client, or `None` when
/// `[custom_extension].url` is unset.
static GLOBAL_CLIENT: OnceLock<Option<Arc<CustomExtensionClient>>> = OnceLock::new();

pub(crate) struct CustomExtensionClient {
    configuration: Configuration,
}

impl CustomExtensionClient {
    /// Return the process-wide custom extension client, or `None` when the
    /// custom extension service URL is not configured.
    pub(crate) fn global() -> Option<Arc<CustomExtensionClient>> {
        GLOBAL_CLIENT
            .get_or_init(|| Self::build_from_config().map(Arc::new))
            .clone()
    }

    fn build_from_config() -> Option<CustomExtensionClient> {
        let config = &ConfigManager::global_config().custom_extension;
        let url = config.url.as_deref()?.trim().to_string();
        if url.is_empty() {
            return None;
        }
        let client = match reqwest::Client::builder()
            .timeout(Duration::from_millis(config.timeout_ms))
            .build()
        {
            Ok(client) => client,
            Err(err) => {
                tracing::warn!(
                    error = %err,
                    "failed to build reqwest client for custom extension; \
                     custom extension integration disabled"
                );
                return None;
            }
        };
        Some(CustomExtensionClient {
            configuration: Configuration {
                base_path: url.trim_end_matches('/').to_string(),
                client,
                ..Configuration::default()
            },
        })
    }

    /// Invoke the start-fresh hook: a fresh sandbox is about to boot.
    ///
    /// Returns extra kernel boot args to append, if any.
    async fn hook_start_fresh(
        &self,
        sandbox_id: SandboxId,
        sandbox_instance_id: SandboxInstanceId,
        network_namespace_path: &str,
        host_interaction_ip: Ipv4Addr,
        custom_extension_params: Option<&CustomExtensionParams>,
    ) -> Result<Option<String>> {
        let request = models::StartFreshHookRequest {
            sandbox_id: sandbox_id.to_string(),
            sandbox_instance_id: sandbox_instance_id.to_string(),
            network_namespace_path: network_namespace_path.to_string(),
            host_interaction_ip: host_interaction_ip.to_string(),
            custom_extension_params: Some(
                custom_extension_params
                    .cloned()
                    .map(serde_json::Value::Object)
                    .unwrap_or_else(empty_params),
            ),
        };
        let response = default_api::sandbox_start_fresh(&self.configuration, request)
            .await
            .context("custom extension start-fresh hook failed")?;
        Ok(response.extra_boot_args.flatten())
    }

    /// Invoke the start-resume hook: a sandbox is about to resume from a snapshot.
    async fn hook_start_resume(
        &self,
        sandbox_id: SandboxId,
        sandbox_instance_id: SandboxInstanceId,
        network_namespace_path: &str,
        host_interaction_ip: Ipv4Addr,
        custom_extension_params: Option<&CustomExtensionParams>,
    ) -> Result<()> {
        let request = models::StartResumeHookRequest {
            sandbox_id: sandbox_id.to_string(),
            sandbox_instance_id: sandbox_instance_id.to_string(),
            network_namespace_path: network_namespace_path.to_string(),
            host_interaction_ip: host_interaction_ip.to_string(),
            custom_extension_params: Some(
                custom_extension_params
                    .cloned()
                    .map(serde_json::Value::Object)
                    .unwrap_or_else(empty_params),
            ),
        };
        default_api::sandbox_start_resume(&self.configuration, request)
            .await
            .context("custom extension start-resume hook failed")?;
        Ok(())
    }

    /// Invoke the patch-params hook: apply an extension-defined patch to the
    /// custom extension params.
    ///
    /// The patch document is passed through verbatim; the hook returns the
    /// updated full params (normalized: an absent or empty-object value means
    /// empty params). A failure rejects the patch.
    pub(crate) async fn hook_patch_params(
        &self,
        sandbox_id: SandboxId,
        patch: serde_json::Map<String, serde_json::Value>,
    ) -> Result<Option<CustomExtensionParams>> {
        let request = models::PatchCustomExtensionParamsHookRequest {
            sandbox_id: sandbox_id.to_string(),
            patch: Some(serde_json::Value::Object(patch)),
        };
        let response = default_api::sandbox_patch_params(&self.configuration, request)
            .await
            .context("custom extension patch-params hook failed")?;
        Ok(match response.custom_extension_params {
            None => None,
            Some(value) => match value {
                serde_json::Value::Object(map) => Some(map),
                other => anyhow::bail!(
                    "custom extension patch-params hook returned non-object params: {other}"
                ),
            },
        })
    }

    /// Invoke the stop hook: a sandbox has stopped.
    ///
    /// Fired whenever a sandbox runtime is torn down — including pause
    /// (which stops the VM process and releases the network namespace after
    /// the paused state is persisted; the subsequent resume creates a fresh
    /// runtime and fires start-resume). Stop notification is best-effort:
    /// delivery failures are logged here and never propagated, so callers
    /// (stop() and Drop) share the same fire-and-forget semantics.
    async fn hook_stop(&self, sandbox_id: SandboxId, sandbox_instance_id: SandboxInstanceId) {
        let request = models::StopHookRequest {
            sandbox_id: sandbox_id.to_string(),
            sandbox_instance_id: sandbox_instance_id.to_string(),
        };
        if let Err(err) = default_api::sandbox_stop(&self.configuration, request).await {
            warn!(
                error = %err,
                sandbox_id = %sandbox_id,
                sandbox_instance_id = %sandbox_instance_id,
                "custom extension stop hook failed"
            );
        }
    }
}

/// RAII guard owning the custom extension lifecycle of one sandbox runtime
/// instance.
///
/// Constructed once per runtime via [`CustomExtensionHookGuard::new`];
/// [`CustomExtensionHookGuard::start_fresh`] /
/// [`CustomExtensionHookGuard::start_resume`] then deliver the corresponding
/// start hook, generating a fresh [`SandboxInstanceId`] and recording it
/// *before* the hook is delivered, so that a start hook whose response was
/// lost (e.g. client-side timeout after the extension processed the request)
/// still gets a matching stop on teardown; an extension that never processed
/// the start ignores the stop because the instance id is not its latest
/// started instance.
/// [`CustomExtensionHookGuard::stop`] delivers the stop hook synchronously
/// (awaited) and clears the instance id; dropping a guard that still holds an
/// instance id fires the stop hook fire-and-forget on the current Tokio
/// runtime (never blocking the drop). The stop hook always carries the
/// instance id established by the start hook, so the extension can ignore
/// stop notifications for superseded instances.
pub(crate) struct CustomExtensionHookGuard {
    client: Arc<CustomExtensionClient>,
    sandbox_id: SandboxId,
    /// Instance id established by the start hook (recorded just before the
    /// hook is delivered); `None` while the guard has not started or after
    /// its stop hook was delivered, in which case this guard is inert.
    sandbox_instance_id: Option<SandboxInstanceId>,
}

impl CustomExtensionHookGuard {
    pub(crate) fn new(client: Arc<CustomExtensionClient>, sandbox_id: SandboxId) -> Self {
        Self {
            client,
            sandbox_id,
            sandbox_instance_id: None,
        }
    }

    /// Invoke the start-fresh hook (a fresh sandbox is about to boot).
    ///
    /// Returns the extra kernel boot args returned by the hook, if any.
    pub(crate) async fn start_fresh(
        &mut self,
        network_namespace_path: &str,
        host_interaction_ip: Ipv4Addr,
        custom_extension_params: Option<&CustomExtensionParams>,
    ) -> Result<Option<String>> {
        // Record the instance id before delivering the hook: if the request
        // fails after the extension already processed it (e.g. client-side
        // timeout), teardown still delivers the matching stop.
        let sandbox_instance_id = SandboxInstanceId::new();
        self.sandbox_instance_id = Some(sandbox_instance_id);
        let extra_boot_args = self
            .client
            .hook_start_fresh(
                self.sandbox_id,
                sandbox_instance_id,
                network_namespace_path,
                host_interaction_ip,
                custom_extension_params,
            )
            .await?;
        debug!(
            sandbox_id = %self.sandbox_id,
            sandbox_instance_id = %sandbox_instance_id,
            "custom extension start-fresh hook delivered"
        );
        Ok(extra_boot_args)
    }

    /// Invoke the start-resume hook (a sandbox is about to resume from a
    /// snapshot).
    pub(crate) async fn start_resume(
        &mut self,
        network_namespace_path: &str,
        host_interaction_ip: Ipv4Addr,
        custom_extension_params: Option<&CustomExtensionParams>,
    ) -> Result<()> {
        // Recorded before delivery for the same reason as `start_fresh`.
        let sandbox_instance_id = SandboxInstanceId::new();
        self.sandbox_instance_id = Some(sandbox_instance_id);
        self.client
            .hook_start_resume(
                self.sandbox_id,
                sandbox_instance_id,
                network_namespace_path,
                host_interaction_ip,
                custom_extension_params,
            )
            .await?;
        debug!(
            sandbox_id = %self.sandbox_id,
            sandbox_instance_id = %sandbox_instance_id,
            "custom extension start-resume hook delivered"
        );
        Ok(())
    }

    /// Deliver the stop hook now and clear the instance id.
    pub(crate) async fn stop(mut self) {
        if let Some(sandbox_instance_id) = self.sandbox_instance_id.take() {
            self.client
                .hook_stop(self.sandbox_id, sandbox_instance_id)
                .await;
        }
    }
}

impl Drop for CustomExtensionHookGuard {
    fn drop(&mut self) {
        let Some(sandbox_instance_id) = self.sandbox_instance_id else {
            return;
        };
        let client = Arc::clone(&self.client);
        let sandbox_id = self.sandbox_id;
        match tokio::runtime::Handle::try_current() {
            Ok(handle) => {
                handle.spawn(async move {
                    client.hook_stop(sandbox_id, sandbox_instance_id).await;
                });
            }
            Err(_) => warn!(
                sandbox_id = %sandbox_id,
                sandbox_instance_id = %sandbox_instance_id,
                "sandbox dropped outside a tokio runtime; skipping lifecycle stop hook"
            ),
        }
    }
}

/// Custom extension params: an opaque JSON object interpreted only by the
/// custom extension. `None` and an empty map are equivalent (empty params).
pub(crate) type CustomExtensionParams = serde_json::Map<String, serde_json::Value>;

/// Empty custom extension params (`{}`).
fn empty_params() -> serde_json::Value {
    serde_json::Value::Object(serde_json::Map::new())
}

/// Whether the given params count as empty (absent or an empty map).
pub(crate) fn custom_extension_params_is_empty(params: Option<&CustomExtensionParams>) -> bool {
    match params {
        None => true,
        Some(map) => map.is_empty(),
    }
}

